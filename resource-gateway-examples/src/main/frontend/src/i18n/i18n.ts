export function normalizeLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const normalized = value.trim().toLowerCase().replace('_', '-');
  if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN';
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en';
  return null;
}

export function resolveInitialLocale({
  search,
  storedLocale,
  browserLocales,
}: {
  search: string;
  storedLocale: string | null;
  browserLocales: readonly string[];
}): Locale {
  const requested = normalizeLocale(new URLSearchParams(search).get('lang'));
  if (requested) return requested;
  const stored = normalizeLocale(storedLocale);
  if (stored) return stored;
  for (const browserLocale of browserLocales) {
    const normalized = normalizeLocale(browserLocale);
    if (normalized) return normalized;
  }
  return DEFAULT_LOCALE;
}

export function translate(
  locale: Locale,
  source: string,
  values: TranslationValues = {},
): string {
  const template = locale === 'zh-CN' ? ZH_CN_MESSAGES[source] ?? source : source;
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, key: string) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ));
}

export function readStoredLocale(): string | null {
  try {
    return window.localStorage?.getItem(LOCALE_STORAGE_KEY) ?? null;
  } catch {
    return null;
  }
}

export function writeStoredLocale(locale: Locale): void {
  try {
    window.localStorage?.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Language switching remains session-usable when storage is blocked.
  }
}

export function replaceLocaleQuery(locale: Locale): void {
  const url = new URL(window.location.href);
  url.searchParams.set('lang', locale);
  window.history.replaceState(window.history.state, '', `${url.pathname}${url.search}${url.hash}`);
}
