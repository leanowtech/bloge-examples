    @Override
    public CreateResult create(CreateCommand command) {
        Objects.requireNonNull(command, "command");
        Instant now = now();
        MirrorSessionProtocolIntegrity.verifyInitial(
                mapper, command.payload(), now);
        SessionStateSpace state = command.payload().state();
        byte[] plaintext = serializePayload(command.payload());
        String envelope = protector.protect(plaintext,
                associatedData(state.scope(), state.sessionId(),
                        state.stateRevision(), command.payload().fingerprint()));
        MirrorSessionDescriptor descriptor = descriptor(
                command.payload(), MirrorSessionDescriptor.Status.ACTIVE,
                now, now, null);
        try {
            CreateMutation mutation = transaction.execute(ignored -> {
                lockCapacity();
                Optional<Row> byRequest = queryOne(
                        SELECT_BY_REQUEST,
                        scopeArgs(state.scope(), command.requestId()));
                if (byRequest.isPresent()) {
                    Row row = byRequest.orElseThrow();
                    if (!command.requestFingerprint().equals(
                            row.createFingerprint())) {
                        throw terminal(CREATE_CONFLICT);
                    }
                    return CreateMutation.replayed(new CreateResult(
                            CreateDisposition.REPLAYED,
                            readDescriptor(row)));
                }
                if (queryOne(SELECT_BY_SESSION, scopeArgs(
                        state.scope(), state.sessionId())).isPresent()) {
                    throw terminal(SESSION_ID_CONFLICT);
                }
                CapacityUsage usage = capacityUsage(now, state.scope());
                requireCreateCapacity(usage, plaintext.length, now);
                jdbc.update("""
                                INSERT INTO mirror_session_state (
                                    tenant_id, organization_id, project_id,
                                    environment_id, region, session_id,
                                    create_request_id, create_fingerprint,
                                    descriptor_json, descriptor_fingerprint,
                                    status, state_revision, world_fingerprint,
                                    state_fingerprint, payload_fingerprint,
                                    payload_envelope, payload_bytes,
                                    lease_owner, lease_fence, lease_expires_at,
                                    expires_at, created_at, updated_at, destroyed_at
                                ) VALUES (
                                    ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?,
                                    NULL, 0, NULL, ?, ?, ?, NULL
                                )
                                """,
                        state.scope().tenantId(),
                        state.scope().organizationId(),
                        state.scope().projectId(),
                        state.scope().environmentId(),
                        state.scope().region(),
                        state.sessionId(),
                        command.requestId(),
                        command.requestFingerprint(),
                        json(descriptor),
                        descriptor.fingerprint(),
                        descriptor.status().name(),
                        descriptor.stateRevision(),
                        descriptor.worldFingerprint(),
                        descriptor.stateFingerprint(),
                        command.payload().fingerprint(),
                        envelope,
                        plaintext.length,
                        descriptor.expiresAt().toString(),
                        descriptor.createdAt().toString(),
                        descriptor.updatedAt().toString());
                appendAudit(state.scope(), state.sessionId(), now,
                        Operation.CREATE, "", descriptor);
                return CreateMutation.created(
                        new CreateResult(
                                CreateDisposition.CREATED, descriptor),
                        globalSnapshot(
                                usage.global().plus(plaintext.length)));
            });
            if (mutation == null) {
                throw retryable(UNAVAILABLE,
                        RETRY_AFTER_UNAVAILABLE_SECONDS);
            }
            if (mutation.capacity() != null) {
                capacityTelemetry.observe(mutation.capacity());
            }
            return mutation.result();
        } catch (DuplicateKeyException duplicate) {
            return replayCreate(command);
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

    @Override
    public Optional<MirrorSessionDescriptor> find(
            CapabilitySnapshot.Scope scope, String sessionId) {
        requireScope(scope);
        String id = required(sessionId, "sessionId");
        try {
            return transaction.execute(ignored -> {
                Optional<Row> found = rowForUpdate(scope, id);
                if (found.isEmpty()) {
                    return Optional.empty();
                }
                Row row = found.orElseThrow();
                Instant now = now();
                if (row.active() && !row.expiresAt().isAfter(now)) {
                    return Optional.of(expire(scope, id, row, now));
                }
                return Optional.of(readDescriptor(row));
            });
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

    @Override
    public SessionSnapshot snapshot(SnapshotCommand command) {
        Objects.requireNonNull(command, "command");
        try {
            SnapshotAttempt attempt = transaction.execute(ignored -> {
                Row row = rowForUpdate(
                        command.scope(), command.sessionId())
                        .orElseThrow(() -> terminal(NOT_FOUND));
                Instant now = now();
                if (row.active() && !row.expiresAt().isAfter(now)) {
                    expire(command.scope(), command.sessionId(), row, now);
                    return SnapshotAttempt.expiredAttempt();
                }
                if (!row.active()) {
                    throw terminal(GONE);
                }
                MirrorSessionPayload payload = decrypt(
                        command.scope(), command.sessionId(), row);
                return SnapshotAttempt.available(new SessionSnapshot(
                        payload, readDescriptor(row)));
            });
            if (attempt == null) {
                throw retryable(
                        UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
            }
            if (attempt.expired()) {
                throw terminal(GONE);
            }
            return attempt.snapshot();
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

    @Override
    public CheckpointSnapshot checkpointSnapshot(
            SnapshotCommand command) {
        Objects.requireNonNull(command, "command");
        try {
            SnapshotAttempt attempt = transaction.execute(ignored -> {
                MirrorSessionStoreGeneration generation =
                        readGeneration();
                Row row = rowForUpdate(
                        command.scope(), command.sessionId())
                        .orElseThrow(() -> terminal(NOT_FOUND));
                Instant now = now();
                if (row.active() && !row.expiresAt().isAfter(now)) {
                    expire(command.scope(), command.sessionId(), row, now);
                    return SnapshotAttempt.expiredAttempt();
                }
                if (!row.active()) {
                    throw terminal(GONE);
                }
                MirrorSessionPayload payload = decrypt(
                        command.scope(), command.sessionId(), row);
                return SnapshotAttempt.available(new SessionSnapshot(
                        payload, readDescriptor(row)), generation);
            });
            if (attempt == null) {
                throw retryable(
                        UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
            }
            if (attempt.expired()) {
                throw terminal(GONE);
            }
            return new CheckpointSnapshot(
                    Objects.requireNonNull(
                            attempt.generation(),
                            "checkpoint snapshot generation"),
                    attempt.snapshot());
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(
                    UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

    @Override
    public ClaimedSession claim(ClaimCommand command) {
        Objects.requireNonNull(command, "command");
        try {
            ClaimAttempt attempt = transaction.execute(ignored -> {
                Row row = rowForUpdate(command.scope(), command.sessionId())
                        .orElseThrow(() -> terminal(NOT_FOUND));
                Instant now = now();
                if (row.active() && !row.expiresAt().isAfter(now)) {
                    expire(command.scope(), command.sessionId(), row, now);
                    return ClaimAttempt.expiredAttempt();
                }
                if (!row.active()) {
                    throw terminal(GONE);
                }
                if (row.leaseExpiresAt() != null
                        && row.leaseExpiresAt().isAfter(now)
                        && !command.ownerId().equals(row.leaseOwner())) {
                    throw retryable(LEASE_BUSY,
                            retryAfter(now, row.leaseExpiresAt()));
                }
                long fence = Math.addExact(row.leaseFence(), 1);
                Instant leaseExpiresAt =
                        now.plusSeconds(command.leaseDurationSeconds());
                int updated = jdbc.update("""
                                UPDATE mirror_session_state
                                   SET lease_owner = ?,
                                       lease_fence = ?,
                                       lease_expires_at = ?
                                 WHERE %s AND session_id = ?
                                   AND lease_fence = ?
                                """.formatted(SCOPE),
                        concatArgs(
                                new Object[]{
                                        command.ownerId(),
                                        fence,
                                        leaseExpiresAt.toString()
                                },
                                scopeArgs(command.scope(), command.sessionId(),
                                        row.leaseFence())));
                if (updated != 1) {
                    throw retryable(LEASE_LOST, 1);
                }
                MirrorSessionPayload payload = decrypt(
                        command.scope(), command.sessionId(), row);
                MirrorSessionDescriptor descriptor = readDescriptor(row);
                Lease lease = new Lease(command.scope(), command.sessionId(),
                        command.ownerId(), fence, leaseExpiresAt);
                return ClaimAttempt.claimed(
                        new ClaimedSession(lease, payload, descriptor));
            });
            if (attempt.expired()) {
                throw terminal(GONE);
            }
            return attempt.session();
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

    @Override
    public boolean release(Lease lease) {
        Objects.requireNonNull(lease, "lease");
        try {
            return Boolean.TRUE.equals(transaction.execute(ignored -> {
                Optional<Row> found = rowForUpdate(
                        lease.scope(), lease.sessionId());
                if (found.isEmpty()) {
                    return false;
                }
                Row row = found.orElseThrow();
                Instant now = now();
                if (row.active() && !row.expiresAt().isAfter(now)) {
                    expire(lease.scope(), lease.sessionId(), row, now);
                    return false;
                }
                if (!row.active()
                        || !lease.ownerId().equals(row.leaseOwner())
                        || lease.fence() != row.leaseFence()) {
                    return false;
                }
                int updated = jdbc.update("""
                                UPDATE mirror_session_state
                                   SET lease_owner = NULL,
                                       lease_expires_at = NULL
                                 WHERE %s AND session_id = ?
                                   AND status = 'ACTIVE'
                                   AND lease_owner = ?
                                   AND lease_fence = ?
                                """.formatted(SCOPE),
                        scopeArgs(lease.scope(), lease.sessionId(),
                                lease.ownerId(), lease.fence()));
                return updated == 1;
            }));
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

    @Override
    public CommitResult compareAndSet(CommitCommand command) {
        Objects.requireNonNull(command, "command");
        MirrorSessionProtocolIntegrity.verify(mapper, command.candidate());
        SessionStateSpace candidateState = command.candidate().state();
        requireCandidateLease(command.lease(), candidateState);
        byte[] plaintext = serializePayload(command.candidate());
        String envelope = protector.protect(plaintext,
                associatedData(candidateState.scope(), candidateState.sessionId(),
                        candidateState.stateRevision(),
                        command.candidate().fingerprint()));
        try {
            CommitAttempt attempt = transaction.execute(ignored -> {
                CapabilitySnapshot.Scope scope = command.lease().scope();
                String sessionId = command.lease().sessionId();
                lockCapacity();
                Row row = rowForUpdate(scope, sessionId)
                        .orElseThrow(() -> terminal(NOT_FOUND));
                Instant now = now();
                if (row.active() && !row.expiresAt().isAfter(now)) {
                    expire(scope, sessionId, row, now);
                    return CommitAttempt.expiredAttempt();
                }
                requireCommitFence(command, row, now);
                MirrorSessionDescriptor previous = readDescriptor(row);
                requireCandidateClosure(previous, candidateState);
                WriteAttemptRow writeAttempt = command.writeAttemptId().isBlank()
                        ? null : requireCommitWriteAttempt(
                        command, candidateState, now);
                CapacityUsage usage = capacityUsage(now, scope);
                requireCommitCapacity(
                        usage, row.payloadBytes(), plaintext.length, now);
                MirrorSessionDescriptor descriptor = descriptor(
                        command.candidate(),
                        MirrorSessionDescriptor.Status.ACTIVE,
                        previous.createdAt(), now, null);
                int updated = jdbc.update("""
                                UPDATE mirror_session_state
                                   SET descriptor_json = ?,
                                       descriptor_fingerprint = ?,
                                       state_revision = ?,
                                       world_fingerprint = ?,
                                       state_fingerprint = ?,
                                       payload_fingerprint = ?,
                                       payload_envelope = ?,
                                       payload_bytes = ?,
                                       updated_at = ?
                                 WHERE %s AND session_id = ?
                                   AND status = 'ACTIVE'
                                   AND state_fingerprint = ?
                                   AND lease_owner = ?
                                   AND lease_fence = ?
                                """.formatted(SCOPE),
                        concatArgs(
                                new Object[]{
                                        json(descriptor),
                                        descriptor.fingerprint(),
                                        descriptor.stateRevision(),
                                        descriptor.worldFingerprint(),
                                        descriptor.stateFingerprint(),
                                        command.candidate().fingerprint(),
                                        envelope,
                                        plaintext.length,
                                        now.toString()
                                },
                                scopeArgs(scope, sessionId,
                                        command.expectedStateFingerprint(),
                                        command.lease().ownerId(),
                                        command.lease().fence())));
                if (updated != 1) {
                    throw retryable(STATE_CONFLICT, 1);
                }
                appendAudit(scope, sessionId, now,
                        Operation.COMMIT, "", descriptor);
                if (writeAttempt != null) {
                    terminalizeCommittedWriteAttempt(
                            writeAttempt, command.candidate(),
                            descriptor, now);
                }
                return CommitAttempt.committed(
                        new CommitResult(descriptor),
                        globalSnapshot(usage.global().replace(
                                row.payloadBytes(), plaintext.length)));
            });
            if (attempt.expired()) {
                throw terminal(GONE);
            }
            capacityTelemetry.observe(attempt.capacity());
            return attempt.result();
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

