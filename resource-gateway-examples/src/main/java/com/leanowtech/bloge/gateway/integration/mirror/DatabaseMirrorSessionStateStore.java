    private MirrorSessionPayload decrypt(
            CapabilitySnapshot.Scope scope, String sessionId, Row row) {
        if (row.payloadEnvelope() == null
                || row.payloadFingerprint() == null
                || row.payloadBytes() < 1
                || row.payloadBytes()
                > MirrorSessionProtocolIntegrity.MAXIMUM_PAYLOAD_BYTES) {
            throw terminal(CORRUPT);
        }
        try {
            byte[] plaintext = protector.unprotect(
                    row.payloadEnvelope(),
                    associatedData(scope, sessionId, row.stateRevision(),
                            row.payloadFingerprint()));
            if (plaintext.length != row.payloadBytes()) {
                throw terminal(CORRUPT);
            }
            MirrorSessionPayload payload =
                    mapper.readValue(plaintext, MirrorSessionPayload.class);
            MirrorSessionProtocolIntegrity.verify(mapper, payload);
            if (!payload.fingerprint().equals(row.payloadFingerprint())
                    || !payload.state().fingerprint().equals(
                    row.stateFingerprint())) {
                throw terminal(CORRUPT);
            }
            return payload;
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (Exception invalid) {
            throw terminal(CORRUPT);
        }
    }

    private byte[] serializePayload(MirrorSessionPayload payload) {
        try {
            byte[] bytes = mapper.writeValueAsBytes(payload);
            if (bytes.length < 1 || bytes.length
                    > MirrorSessionProtocolIntegrity.MAXIMUM_PAYLOAD_BYTES) {
                throw retryable(
                        MirrorSessionStateStoreException.Code.CAPACITY_EXCEEDED, 1);
            }
            return bytes;
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (JsonProcessingException invalid) {
            throw terminal(CORRUPT);
        }
    }

