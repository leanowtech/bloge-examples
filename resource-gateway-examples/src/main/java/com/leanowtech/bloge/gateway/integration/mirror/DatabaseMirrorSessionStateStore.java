    @Override
    public DestroyResult destroy(
            CapabilitySnapshot.Scope scope, String sessionId) {
        requireScope(scope);
        String id = required(sessionId, "sessionId");
        try {
            return transaction.execute(ignored -> {
                Row row = rowForUpdate(scope, id)
                        .orElseThrow(() -> terminal(NOT_FOUND));
                MirrorSessionDescriptor current = readDescriptor(row);
                if (current.status() == MirrorSessionDescriptor.Status.DESTROYED) {
                    return new DestroyResult(
                            DestroyDisposition.ALREADY_DESTROYED, current);
                }
                if (current.status() == MirrorSessionDescriptor.Status.EXPIRED) {
                    return new DestroyResult(
                            DestroyDisposition.EXPIRED, current);
                }
                Instant now = now();
                if (!row.expiresAt().isAfter(now)) {
                    return new DestroyResult(
                            DestroyDisposition.EXPIRED,
                            expire(scope, id, row, now));
                }
                MirrorSessionDescriptor destroyed = terminalize(
                        scope, id, row, now,
                        MirrorSessionDescriptor.Status.DESTROYED,
                        Operation.DESTROY);
                return new DestroyResult(
                        DestroyDisposition.DESTROYED, destroyed);
            });
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE, RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

    @Override
    public int expireDue(int limit) {
        if (limit < 1 || limit > MAXIMUM_EXPIRY_SWEEP_BATCH) {
            throw new IllegalArgumentException(
                    "mirror expiry sweep limit must be between 1 and "
                            + MAXIMUM_EXPIRY_SWEEP_BATCH);
        }
        try {
            ExpirySweep sweep = transaction.execute(ignored -> {
                lockCapacity();
                Instant now = now();
                List<SessionCoordinate> due = jdbc.query("""
                                SELECT tenant_id, organization_id, project_id,
                                       environment_id, region, session_id
                                  FROM mirror_session_state
                                 WHERE status = 'ACTIVE'
                                   AND expires_at <= ?
                                 ORDER BY expires_at,
                                          tenant_id, organization_id,
                                          project_id, environment_id,
                                          region, session_id
                                 LIMIT ?
                                """,
                        (rs, rowNum) -> new SessionCoordinate(
                                new CapabilitySnapshot.Scope(
                                        rs.getString("tenant_id"),
                                        rs.getString("organization_id"),
                                        rs.getString("project_id"),
                                        rs.getString("environment_id"),
                                        rs.getString("region")),
                                rs.getString("session_id")),
                        now.toString(), limit);
                int expired = 0;
                for (SessionCoordinate coordinate : due) {
                    Optional<Row> found = rowForUpdate(
                            coordinate.scope(), coordinate.sessionId());
                    if (found.isEmpty()) {
                        continue;
                    }
                    Row row = found.orElseThrow();
                    if (row.active()
                            && !row.expiresAt().isAfter(now)) {
                        expire(coordinate.scope(),
                                coordinate.sessionId(), row, now);
                        expired++;
                    }
                }
                return new ExpirySweep(
                        expired, globalSnapshot(globalCapacity(now)));
            });
            if (sweep == null) {
                throw retryable(UNAVAILABLE,
                        RETRY_AFTER_UNAVAILABLE_SECONDS);
            }
            capacityTelemetry.observe(sweep.capacity());
            return sweep.expired();
        } catch (MirrorSessionStateStoreException expected) {
            throw expected;
        } catch (DataAccessException failure) {
            throw retryable(UNAVAILABLE,
                    RETRY_AFTER_UNAVAILABLE_SECONDS);
        }
    }

