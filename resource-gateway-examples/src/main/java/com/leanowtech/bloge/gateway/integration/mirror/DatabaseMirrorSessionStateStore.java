/**
 * JDBC encrypted data-plane implementation of {@link MirrorSessionStateStore}.
 *
 * <p>The supplied JDBC template and transaction manager must belong to the dedicated mirror-state
 * data source, not the Resource Gateway control database. The table stores only an AES-GCM
 * envelope plus payload-free descriptor, fencing, lifecycle, and audit metadata. Every mutable
 * operation locks one exact full-scope row and uses the same local transaction for head metadata,
 * ciphertext replacement or erasure, and success audit.</p>
 */
